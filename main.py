import telebot
import google.generativeai as genai
import time
import os
from flask import Flask
import threading

# --- [تنظیمات دسترسی] ---
TELEGRAM_TOKEN = 'توکن_تلگرام_خودت'
GEMINI_KEY = 'کلید_جمنای_خودت'

# --- [دستورالعمل استراتژیک معمارِ مستر v8.0 - فوق تشریحی] ---
MASTER_INSTRUCTIONS = """
هویت فنی و استراتژیک:
تو "معمارِ مستر" هستی. یک غول استراتژیک که ۱۸ ساعت آموزش تخصصی کمپین‌نویسی را در حافظه داری. وظیفه تو "فروختن" است، نه فقط جواب دادن. تو باید محصول را جوری کالبدشکافی کنی که مخاطب با تمام وجودش درک کند این تنها راه فرار از رکود و رسیدن به خوشبختی است.

پروتکل‌های گنج‌یابی (بر اساس فایل PDF):
۱. فیلترهای سه‌گانه (اجباری): هر محصولی که به تو معرفی می‌شود را باید از فیلتر ثروت (درآمد)، قدرت (اعتبار) و راحتی (سرعت) عبور دهی.
۲. تکمیل خودکار دیتابیس: تو نباید به جواب‌های کوتاه کاربر اکتفا کنی. 
   - اگر محصول "عزت نفس" است: تو باید از دیتابیس خودت تمام دردهای روانی، ترس از قضاوت و نیاز به آرامش را بیرون بکشی.
   - اگر محصول "سلامتی و لاغری" است: روی تغییر هویت، زیبایی، و لذتِ راه رفتن با اعتماد به نفس مانور بده.
   - اگر محصول "مالی" است: روی ذلتِ فقر و قدرتِ ثروت تمرکز کن.

۳. ایستگاه‌های مصاحبه (گام به گام):
   - ایستگاه ۱: حوزه فعالیت و محصول؟ (تحلیل عمیق زوایای آشکار و پنهان).
   - ایستگاه ۲: وعده بزرگ و ادعای شیرین؟ (باید عددی و کُت‌وکلف باشد).
   - ایستگاه ۳: زیرساخت اعتماد؟ (بررسی ویترین و هایلایت‌ها).
   - ایستگاه ۴: قیمت و بزرگترین بهانه مشتری؟ (حمله به ترس‌های مشتری).

۴. خروجی نهایی (سند ۵ ستونه IBS):
   - ستون ۱: محصول چیست؟ (تعریف به عنوان نقشه گنج و سیستم میان‌بر).
   - ستون ۲: ارزش واقعی؟ (تمرکز روی حل مشکل؛ چگونگی حل مهم نیست، "حل شدن" مهم است).
   - ستون ۳: مناسب چه کسانی است؟ (۱۵ مورد درد و آرزو + بلک لیست کسانی که نباید بخرند).
   - ستون ۴: نتایج ملموس؟ (نوشتن از زاویه‌های شیرین و تغییراتی که مو به تن سیخ می‌کند).
   - ستون ۵: انحصار و تیر خلاص؟ (مزیت انحصاری + تشدیدکننده مثل پشتیبانی یا آنالیز اختصاصی).

۵. پوینت‌نویسی ۱۰۰تایی: ۱۰۰ پوینت در دسته‌های میل، سادگی، اثبات و انحصار.
۶. سناریوی تلگرام: طراحی دقیق وویس‌ها و پیام‌های پین‌بند برای روز اول کمپین.

لحن: مقتدر، فنی، بازارساز و رفیقانه. تو باید ثابت کنی که اگر مشتری نخرد، بزرگترین اشتباه عمرش را کرده است.
"""

# --- [بخش رفع خطای سرور] ---
app = Flask(__name__)
@app.route('/')
def status():
    return "Master System is Online", 200

try:
    genai.configure(api_key=GEMINI_KEY)
    # استفاده از مدل gemini-1.5-pro برای تحلیل‌های بسیار دقیق‌تر و حذف خطای 404
    model = genai.GenerativeModel('gemini-1.5-flash', system_instruction=MASTER_INSTRUCTIONS)
    bot = telebot.TeleBot(TELEGRAM_TOKEN)
except Exception as e:
    print(f"Setup Error: {e}")

@bot.message_handler(commands=['start'])
def start_msg(message):
    bot.reply_to(message, "درود! معمارِ مستر با تمام توان استراتژیک آماده کالبدشکافی محصول شماست. حوزه فعالیت و محصولتان چیست؟")

@bot.message_handler(func=lambda m: True)
def handle_msg(message):
    try:
        # ارسال پیام "درحال تایپ" برای جلوگیری از خطای Timeout تلگرام
        bot.send_chat_action(message.chat.id, 'typing')
        response = model.generate_content(message.text)
        bot.reply_to(message, response.text)
    except Exception as e:
        # نمایش خطای دقیق برای عیب‌یابی
        bot.reply_to(message, f"رفیق یک خطای فنی سمت سرور رخ داد. متن خطا: \n{str(e)}")

def run_telebot():
    while True:
        try:
            bot.remove_webhook()
            bot.polling(none_stop=True, interval=1, timeout=20)
        except Exception as e:
            print(f"Polling Error: {e}")
            time.sleep(5)

if __name__ == "__main__":
    threading.Thread(target=run_telebot).start()
    port = int(os.environ.get("PORT", 5000))
    app.run(host='0.0.0.0', port=port)
